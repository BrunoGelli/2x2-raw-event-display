'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = {Float64Array, Uint8Array, DataView, ArrayBuffer, Math, Number, Set};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../raw_display/static/trigger_view.js'), 'utf8'), context);
const ui = context.rawTriggerUI;
ui.configure({time_basis:'asic',trigger_view_enabled:true,n_pixels:4});
ui.state.mode = 'only';
ui.state.tagged[1] = 1000;
const brightness = new Uint8Array([255,0]);
let active = new Uint8Array([0,0,0,255]), empty = new Uint8Array([0,0,0,255]);
ui.setTheme('light');
ui.paint(active,0,1,1000,brightness,255);
ui.paint(empty,0,2,1000,brightness,0);
assert.deepEqual([...active], [143,95,0,255]);
assert.deepEqual([...empty], [244,248,251,255]);
ui.setTheme('dark');
ui.paint(empty,0,2,1000,brightness,0);
assert.deepEqual([...empty], [4,13,20,255]);
console.log('Light beam-candidate contrast and blank-pixel appearance passed.');
