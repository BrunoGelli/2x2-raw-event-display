const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const ctx={};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path.join(__dirname,'../raw_display/static/drift_data.js'),'utf8'),ctx);
